package com.vjstb.ledscheme.settings;

/**
 * Как рисовать «мостики» — обходы в местах пересечения соединительных линий общей
 * схемы (замена прежнего булева {@code UserProfile.schemaWireHops}; ось «сверху та
 * линия, чей сегмент длиннее» и «только внешний вид, на сигнал и питание сразу»
 * не изменилась). Три режима:
 *
 * <ul>
 *   <li>{@link #NONE} — не рисовать обходы вовсе, простое перекрестье (было
 *   по умолчанию; на плотной схеме десятки дуг скорее мешают).</li>
 *   <li>{@link #ARC} — полукруглая (кубическая) дуга: как в ГОСТ, компактная,
 *   но у широкого слитого пролёта над несколькими близкими линиями просвет
 *   тает к краям.</li>
 *   <li>{@link #TRUNCATED} — «усечённая дуга» с плоской вершиной: подъём на
 *   радиус, горизонтальная полка, спуск — просвет держится по всей ширине
 *   пролёта, поэтому лучше для случая «две близкие линии под одной дугой».</li>
 * </ul>
 *
 * <p>Геометрию строит {@link com.vjstb.ledscheme.ui.WireHopGeometry} — там свой
 * локальный enum формы дуги ({@code ArcShape}), чтобы чистая математика не
 * зависела от пакета настроек; {@code SchemaCanvasPanel} отображает эти значения
 * одно в одно.</p>
 */
public enum WireHopStyle {
    NONE("Не рисовать обходы"),
    ARC("Дуга (полукруглая)"),
    TRUNCATED("Усечённая дуга (плоская вершина)");

    private final String label;

    WireHopStyle(String label) {
        this.label = label;
    }

    public String getLabel() {
        return label;
    }

    @Override
    public String toString() {
        return label;
    }
}
