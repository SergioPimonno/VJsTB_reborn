package com.vjstb.ledscheme.settings;

/** Режим отрисовки общей схемы (docs/schema-ports-rework/PLAN.md, задача T5.5,
 *  решение D16) — переключатель «старый способ рисования», добавленный
 *  пользователем ПОСЛЕ того, как этапы 1–4 этого же плана заменили
 *  дорефакторинговый рендер {@code SchemaCanvasPanel} новым (гнёзда на рамке
 *  через {@code NodePortLayout}, роли интерфейсов, ориентация блока,
 *  ортогональная трассировка) без сохранения старого пути (см. DIALOG.md,
 *  реплика 4 — "некоторым людям нравится старый способ рисования схем").
 *
 * <ul>
 *   <li>{@link #MODERN} — текущий рендер этапов 1–4: гнёзда на рамке блока,
 *   роли, 4 ориентации, орто-трассировка, перетаскивание групп гнёзд, сетевые
 *   блоки-устройства. Значение по умолчанию — переключатель это
 *   ДОПОЛНИТЕЛЬНАЯ свобода, а не смена поведения по умолчанию.</li>
 *   <li>{@link #CLASSIC} — дорефакторинговый рендер и хит-тестинг {@code
 *   SchemaCanvasPanel} один в один, как до этого плана (гнёзда строкой у
 *   одного из краёв блока, без ролей/ориентации/орто-трассировки/
 *   перетаскивания групп/сетевых блоков-устройств).</li>
 * </ul>
 *
 * <p>Настройка глобальная — в {@link UserProfile}, не по проекту/сцене (прямой
 * ответ пользователя на вопрос координатора, см. DIALOG.md, реплика 4).
 */
public enum SchemaRenderMode {
    MODERN("Современный"),
    CLASSIC("Классический");

    private final String label;

    SchemaRenderMode(String label) {
        this.label = label;
    }

    public String getLabel() {
        return label;
    }

    @Override
    public String toString() {
        return label;
    }
}
