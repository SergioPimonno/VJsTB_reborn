package com.vjstb.ledscheme.settings;

/**
 * Как показываются НЕзадействованные группы разъёмов на блоке общей схемы (docs/
 * schema-ports-rework/PLAN.md, задача T1.5, D5) — заменяет собой прежний {@link
 * ConnectorDisplayMode}: та настройка решала одно и то же для ВСЕХ групп сразу и не
 * учитывала занятость (была ли к группе подведена связь); эта учитывает.
 *
 * <ul>
 *   <li>{@link #ALWAYS_COLLAPSED} (умолчание) — группа ВСЕГДА рисуется одним
 *   гнездом "N×Тип", даже если к ней подведены линии — поведение старого режима
 *   до переработки T2–T3, к которому пользователь попросил вернуться после того,
 *   как увидел T3.2 в живую (реплика пользователя 2026-09-17: "мне не очень
 *   нравится механика автоматической развертки портов... порты 1 типа
 *   группируются в 1 гнездо, даже при подключении к ним линий" — отменяет более
 *   раннее решение D5 от 2026-09-16 "незанятые сворачиваются, задействованные
 *   включаются", см. {@link #AUTO}).</li>
 *   <li>{@link #AUTO} — группа БЕЗ единой связи сворачивается в одно гнездо
 *   "N×Тип", как только к ней подводят хотя бы одну линию — разворачивается в N
 *   пронумерованных гнёзд (исходное решение D5, см. выше — оставлено как опция
 *   для тех, кому такое поведение всё же нужно).</li>
 *   <li>{@link #ALWAYS_EXPANDED} — ВСЕ группы держатся развёрнутыми независимо от
 *   занятости, как раньше вело себя {@link ConnectorDisplayMode#INDIVIDUAL} —
 *   полезно, когда нужно расключать многоканальное оборудование по конкретным
 *   номерам разъёмов ещё до того, как они использованы.</li>
 * </ul>
 *
 * <p>Пользователь может дополнительно принудительно свернуть/развернуть ОТДЕЛЬНУЮ
 * группу (см. {@code PortPlacement#getCollapsed()}) независимо от этой глобальной
 * настройки — та решает только поведение по умолчанию для непереопределённых групп.
 */
public enum GroupDisplayMode {
    ALWAYS_COLLAPSED("Всегда свёрнуты"),
    AUTO("Авто (по занятости)"),
    ALWAYS_EXPANDED("Всегда развёрнуты");

    private final String label;

    GroupDisplayMode(String label) {
        this.label = label;
    }

    public String getLabel() {
        return label;
    }

    @Override
    public String toString() {
        return label;
    }
}
