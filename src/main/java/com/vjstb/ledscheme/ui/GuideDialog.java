    private final SettingsManager settings;
    private final JTabbedPane tabs = new JTabbedPane();

    public GuideDialog(Window owner, SettingsManager settings) {
        super(owner, "Руководство", ModalityType.MODELESS);
        this.settings = settings;

        rebuildTabs();

        JPanel content = new JPanel(new BorderLayout());
        content.add(tabs, BorderLayout.CENTER);
        JPanel bottom = new JPanel(new java.awt.FlowLayout(java.awt.FlowLayout.RIGHT));
        JButton close = new JButton("Закрыть");
        close.addActionListener(e -> dispose());
        bottom.add(close);
        content.add(bottom, BorderLayout.SOUTH);

        setContentPane(content);
        setSize(660, 520);
        setLocationRelativeTo(owner);
    }

    private List<ContentSection> sections() {
        List<ContentSection> custom = settings.getCustomContent(CONTENT_KEY);
        return custom != null && !custom.isEmpty() ? custom : DEFAULT_SECTIONS;
    }

    private void rebuildTabs() {
        int selected = tabs.getSelectedIndex();
        tabs.removeAll();
        for (ContentSection s : sections()) {
            tabs.addTab(s.getTitle(), section(s.getBodyHtml()));
        }
        if (selected >= 0 && selected < tabs.getTabCount()) {
            tabs.setSelectedIndex(selected);
        }
    }

    /** Открывает редактор текста руководства — вызывается из AdminDialog
     *  (Инструменты → «Админ-режим…» → «Тексты»), больше не из кнопки в самом
     *  диалоге руководства. */
    public void openEditor() {
        ContentEditorDialog dlg = new ContentEditorDialog(this, "Редактировать руководство", sections(),
                DEFAULT_SECTIONS, saved -> {
                    settings.setCustomContent(CONTENT_KEY, saved);
                    rebuildTabs();
                });
        dlg.setVisible(true);
    }

    private JScrollPane section(String html) {
        JPanel body = new JPanel(new BorderLayout());
        body.setBorder(BorderFactory.createEmptyBorder(12, 14, 12, 14));
        JLabel label = new JLabel("<html><body style='width: 460px'>" + html + "</body></html>");
        body.add(label, BorderLayout.NORTH);
        JScrollPane scroll = new JScrollPane(body);
        scroll.setBorder(BorderFactory.createEmptyBorder());
        scroll.getVerticalScrollBar().setUnitIncrement(16);
        return scroll;
    }
