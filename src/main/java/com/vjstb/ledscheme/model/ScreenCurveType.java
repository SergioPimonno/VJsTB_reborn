package com.vjstb.ledscheme.model;

/**
 * Форма экрана в плане для НАЗЕМНОГО конструктива (запрос пользователя 2026-10-01): изгиб
 * только по горизонтали (вокруг вертикальной оси), по вертикали экран всегда прямой.
 * Осмысленна только при {@link ScreenMountType#STRUCTURE} — подвес, фермы и круглые фермы
 * изгибом не затрагиваются (отложено пользователем до версии 3.0). Развёрнутая ширина
 * экрана, кабинеты, маски, сигнал и питание от изгиба не зависят — меняется только
 * расстановка башен конструктива и картинка в 3D (см. {@code service.StructureCurveMath},
 * STRUCTURE_CALC_NOTES.md, раздел «Изогнутые экраны»).
 *
 * <p>{@link #FLAT} — значение по умолчанию: старые проекты без поля открываются прямыми и
 * считаются ровно как раньше.
 */
public enum ScreenCurveType {
    /** Прямой экран — поведение до 2026-10-01. */
    FLAT("Прямой"),
    /** Вогнутый: центр кривизны со стороны зрителя, экран «обнимает» зрителя. */
    CONCAVE("Вогнутый"),
    /** Выпуклый: экран выгнут в сторону зрителя, центр кривизны за экраном. */
    CONVEX("Выпуклый");

    private final String label;

    ScreenCurveType(String label) {
        this.label = label;
    }

    public String getLabel() {
        return label;
    }

    public boolean isCurved() {
        return this != FLAT;
    }

    @Override
    public String toString() {
        return label;
    }
}
